# Inisialisasi data nilai
nilai = [75, 80, 65, 90, 88]

print("3. Indeks dan Slicing")
print("List lengkap:", nilai)

# Mengakses elemen berdasarkan indeks positif dan negatif
print("nilai[0] =", nilai[0])       
print("nilai[2] =", nilai[2])       
print("nilai[-1] =", nilai[-1])    

# Melakukan Slicing (memotong list)
print("nilai[1:4] =", nilai[1:4])   
print("nilai[:3] =", nilai[:3])     
print("nilai[::2] =", nilai[::2])   