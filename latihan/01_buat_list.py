# 1. Membuat list numerik untuk nilai mahasiswa (Sesuai Prinsip)
# Menggunakan list numerik memudahkan operasi matematika seperti sum() dan len()
nilai_mahasiswa = [75, 80, 65, 90, 88]

# Contoh operasi matematika pada list numerik
total_nilai = sum(nilai_mahasiswa)
rata_rata = total_nilai / len(nilai_mahasiswa)

print("--- Data Nilai Mahasiswa ---")
print("Daftar Nilai:", nilai_mahasiswa)
print("Total Nilai:", total_nilai)
print("Rata-rata Nilai:", rata_rata)

